#!/bin/bash
# Скрипт выводит приветствие с именем пользователя с большой буквы

# 1. Вывод "Tere, " без переноса строки
echo -n "Tere, "

# 2. Получаем имя пользователя и преобразуем первую букву в заглавную
kasutaja=$(whoami | awk '{print toupper(substr($0,1,1)) substr($0,2)}')
echo -n "$kasutaja"

# 3. Вывод "!" с переносом строки
echo "!"
